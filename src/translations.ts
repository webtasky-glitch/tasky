export function useTranslation() {
  const { language } = useTasky() as any;
  const lang = (language || 'el') as Language;
  
  const t = (key: keyof typeof translationDict.en | keyof typeof translationDict.el | string): string => {
    return (translationDict[lang] as any)?.[key] || (translationDict['en'] as any)?.[key] || String(key);
  };

  const tPriority = (priority?: string): string => {
    const p = String(priority || '');
    if (lang === 'el') {
      if (p === 'Low') return 'Χαμηλή';
      if (p === 'Medium') return 'Μεσαία';
      if (p === 'High') return 'Υψηλή';
      if (p === 'Urgent') return 'Επείγουσα';
    }
    return p;
  };

  const tStatus = (status?: string): string => {
    const s = String(status || '');
    if (lang === 'el') {
      if (s === 'Todo') return 'Προς Υλοποίηση';
      if (s === 'InProgress' || s === 'In Progress') return 'Σε Εξέλιξη';
      if (s === 'Completed') return 'Ολοκληρωμένο';
    }
    return s;
  };

  const tRecurring = (rec?: string): string => {
    const r = String(rec || '');
    if (lang === 'el') {
      if (r === 'None') return 'Καμία';
      if (r === 'Daily') return 'Καθημερινά';
      if (r === 'Weekly') return 'Εβδομαδιαία';
      if (r === 'Monthly') return 'Μηνιαία';
    }
    return r;
  };

  const tFocusBlock = (slot?: string): string => {
    const s = String(slot || '');
    if (lang === 'el') {
      if (s === 'MorningFocus') return '🌅 Πρωινή Εστίαση';
      if (s === 'AfternoonDeep') return '⚡ Απογευματινή Συγκέντρωση';
      if (s === 'QuickAdmin') return '☕ Γρήγορες Διαχειριστικές Εργασίες';
      if (s === 'EveningReview') return '🌙 Βραδινή Ανασκόπηση';
    } else {
      if (s === 'MorningFocus') return '🌅 Morning Focus';
      if (s === 'AfternoonDeep') return '⚡ Afternoon Deep';
      if (s === 'QuickAdmin') return '☕ Quick Admin';
      if (s === 'EveningReview') return '🌙 Evening Review';
    }
    return s || (lang === 'el' ? '🌅 Πρωινή Εστίαση' : '🌅 Morning Focus');
  };

  const tRelativeDate = (dateStr: string): string => {
    if (!dateStr) return '';
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const tomorrow = new Date();
    tomorrow.setDate(tomorrow.getDate() + 1);
    tomorrow.setHours(0, 0, 0, 0);
    const yesterday = new Date();
    yesterday.setDate(yesterday.getDate() - 1);
    yesterday.setHours(0, 0, 0, 0);

    const checkDate = new Date(dateStr);
    checkDate.setHours(0, 0, 0, 0);

    if (checkDate.getTime() === today.getTime()) return lang === 'el' ? 'Σήμερα' : 'Today';
    if (checkDate.getTime() === tomorrow.getTime()) return lang === 'el' ? 'Αύριο' : 'Tomorrow';
    if (checkDate.getTime() === yesterday.getTime()) return lang === 'el' ? 'Χθες' : 'Yesterday';
    return dateStr;
  };
  
  return { t, language: lang, tPriority, tStatus, tRecurring, tFocusBlock, tRelativeDate };
}
